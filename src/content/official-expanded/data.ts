const categoryQuery = `SELECT c.category_id,
       c.name AS category_name,
       COALESCE(p.name, '최상위') AS parent_name
FROM Category AS c
LEFT JOIN Category AS p
  ON c.parent_id = p.category_id
ORDER BY c.category_id;`;

