type Entry = readonly [text: string, explanation: string];
function choice(
  number: number,
  topic: string,
  prompt: string,
  entries: [Entry, Entry, Entry, Entry],
  answer: number,
  explanation: string,
  keyPoints: string[],
  stimulus?: string,
): Question {
  return {
    ...base(number, topic),
    kind: "choice",
    points: 5,
    difficulty: "응용",
    prompt,
    stimulus,
    options: entries.map(([text, why], index) => ({
      id: String(index + 1),
      text,
      explanation: `${index + 1 === answer ? "정답" : "오답"}. ${why}`,
    })),
    answer: String(answer),
    modelAnswer: `${answer}번. ${entries[answer - 1][0]}`,
    explanation,
    keyPoints,
  };
}

