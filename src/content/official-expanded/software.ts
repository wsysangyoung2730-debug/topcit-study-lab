type ChoiceEntry = readonly [text: string, explanation: string];
type ChoiceInput = {
  number: number;
  topic: string;
  prompt: string;
  stimulus: string;
  choices: [ChoiceEntry, ChoiceEntry, ChoiceEntry, ChoiceEntry];
  answer: 1 | 2 | 3 | 4;
  explanation: string;
  keyPoints: string[];
  sources?: SourceRef[];
  difficulty?: Question["difficulty"];
};

function choice(input: ChoiceInput): Question {
  return {
    id: `official-q${input.number}`,
    round: 0,
    domain: "software",
    kind: "choice",
    points: 5,
    difficulty: input.difficulty ?? "응용",
    topic: input.topic,
    title: `공개 문항 ${input.number} 기반 재구성`,
    prompt: input.prompt,
    stimulus: input.stimulus,
    options: input.choices.map(([text, explanation], index) => ({
      id: String(index + 1),
      text,
      explanation: `${input.answer === index + 1 ? "정답" : "오답"}. ${explanation}`,
    })),
    answer: String(input.answer),
    modelAnswer: `${input.answer}번. ${input.choices[input.answer - 1][0]}`,
    explanation: input.explanation,
    keyPoints: input.keyPoints,
    sources: [officialSource(input.number), ...(input.sources ?? [])],
    origin: "reference-adapted",
  };
}

